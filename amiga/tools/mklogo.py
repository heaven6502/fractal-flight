"""mklogo.py - the intro logo of the Amiga flight: ../gfx/desire_logo32c.png (320 x 200, 32 colours) -> gfx/desire_logo32c.bpl (5 bitplanes of 8000 bytes: plane 0 first, every plane 200 rows of 40 bytes,
MSB = the leftmost pixel) and src/logo_pal.h (the 32 colours as OCS words 0x0RGB, 4 bits per channel).   usage: python tools/mklogo.py"""
import os
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(HERE, "..", "..", "gfx", "desire_logo32c.png")
im = Image.open(src)
assert im.size == (320, 200) and im.mode == "P", (im.size, im.mode)
pal = im.getpalette()[:96]
words = [((round(pal[i * 3] * 15 / 255)) << 8) | ((round(pal[i * 3 + 1] * 15 / 255)) << 4) | round(pal[i * 3 + 2] * 15 / 255) for i in range(32)]
px = im.load()
planes = bytearray()
for p in range(5):
    for y in range(200):
        for xb in range(40):
            v = 0
            for k in range(8):
                v = (v << 1) | ((px[xb * 8 + k, y] >> p) & 1)
            planes.append(v)
os.makedirs(os.path.join(HERE, "..", "gfx"), exist_ok=True)
open(os.path.join(HERE, "..", "gfx", "desire_logo32c.bpl"), "wb").write(planes)
open(os.path.join(HERE, "..", "src", "logo_pal.h"), "w", newline="\n").write("/* logo_pal.h - generated by tools/mklogo.py from gfx/desire_logo32c.png: the 32 colours of the intro logo, OCS 0x0RGB */\nstatic const unsigned short logoPal[32] = {\n\t" + ", ".join("0x%03X" % w for w in words[:16]) + ",\n\t" + ", ".join("0x%03X" % w for w in words[16:]) + "\n};\n")
print("gfx/desire_logo32c.bpl written (%d bytes), src/logo_pal.h" % len(planes), " ".join("%03X" % w for w in words))
