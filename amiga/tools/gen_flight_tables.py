"""Writes src/flight_data.c: the tables of the fractal flight.
  fSinHi / fSinLo        sine tables of the game (jaggie_data.pbi)
  fWalkLegacy / fEdgesLegacy   the game's fan: 4 walk tables of 45 steps, 72 edges (jaggie_data.pbi)
  fWalkFar / fEdgesFar         the FAR fan of the latest iron port: 4 walk tables of 55 steps, 90 edges (flight800\\tables_far.asm)
usage: python tools/gen_flight_tables.py"""
import os, re

ROF = r"C:\coding\Atari\rof"
HERE = os.path.dirname(os.path.abspath(__file__))

def pbi_table(txt, label, n):
    m = re.search(label + r":[^\n]*\n((?:\s*Data\.a [^\n]*\n)+)", txt)
    vals = [int(x, 16) for x in re.findall(r"\$([0-9A-Fa-f]{2})", m.group(1))]
    assert len(vals) >= n, (label, len(vals))
    return vals[:n]

def asm_table(txt, label, n):
    m = re.search(r"^" + label + r"[^\n]*\n((?:\s*\.byte [^\n]*\n)+)", txt, re.M)
    vals = [int(x, 16) for x in re.findall(r"\$([0-9A-Fa-f]{2})", m.group(1))]
    assert len(vals) == n, (label, len(vals))
    return vals

pbi = open(os.path.join(ROF, "jaggie_data.pbi")).read() + open(os.path.join(ROF, "jaggie_flight.pbi")).read()
far = open(os.path.join(ROF, "flight800", "tables_far.asm")).read()
tables = [
    ("fSinHi", pbi_table(pbi, "SinData", 65), 16),
    ("fSinLo", pbi_table(pbi, "SinLoData", 65), 16),
    ("fWalkLegacy", pbi_table(pbi, "WalkData", 180), 15),
    ("fEdgesLegacy", pbi_table(pbi, "EdgeData", 144), 16),
    ("fWalkFar", asm_table(far, "WALK", 220), 16),
    ("fEdgesFar", asm_table(far, "EDGES", 180), 16),
]

def block(name, vals, per):
    rows = [", ".join("0x%02X" % v for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return "const unsigned char %s[%d] = {\n    %s\n};\n" % (name, len(vals), ",\n    ".join(rows))

open(os.path.join(HERE, "..", "src", "flight_data.c"), "w", newline="\n").write(
    "/* flight_data.c - tables of Behind Jaggi Lines! (generated by tools/gen_flight_tables.py, do not edit) */\n"
    "#include \"flight_core.h\"\n\n" + "".join(block(*t) for t in tables))
print("src/flight_data.c written:", ", ".join("%s[%d]" % (n, len(v)) for n, v, _ in tables))
