#!/usr/bin/env python3
"""gfx/gyrussplanets.png (the planets of Gyruss on a magenta sheet, each on a dark purple box = transparent) -> src/gyruss_planets.h
For each planet: 8 colours (the sprite colour registers 17 .. 24: the pixel codes 1 .. 8, 0 = transparent) and the lines as sprite words for the
four attached sprites of the sun: per line 8 words = {a, b, c, d} of the left 16 pixels, {a, b, c, d} of the right 16 pixels (bit 0 .. 3 of the code).
The planet is centred in a window of 32 x ROWS pixels; wider ones (the Earth) are scaled down to 32."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pngload import load
ROWS = 42
W, H, px = load(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'gfx', 'gyrussplanets.png'))
BG = (255, 0, 220); BOX = (127, 0, 110)
# name, x0, x1, y0, y1 (the box of the planet on the sheet)
PL = []                                  # the planets of Gyruss (Earth, Neptune, Uranus, Saturn, Jupiter, Mars) are gone: planetgen.c makes planets at run time

def opaque(p): return p != BG and p != BOX

def crop(x0, x1, y0, y1):
    return [[px[y][x] for x in range(x0, x1 + 1)] for y in range(y0, y1 + 1)]

def scale_to_width(img, tw):
    h, w = len(img), len(img[0])
    if w <= tw: return img
    f = w / tw; th = max(1, round(h / f)); out = []
    for ty in range(th):
        row = []
        for tx in range(tw):
            xs0, xs1 = tx * f, (tx + 1) * f; ys0, ys1 = ty * f, (ty + 1) * f
            acc = [0, 0, 0]; n = 0; tot = 0
            for y in range(int(ys0), min(h, int(ys1 + 0.999))):
                for x in range(int(xs0), min(w, int(xs1 + 0.999))):
                    tot += 1
                    if opaque(img[y][x]):
                        n += 1
                        for k in range(3): acc[k] += img[y][x][k]
            row.append(tuple(a // n for a in acc) if n * 2 >= tot and n else BG)
        out.append(row)
    return out

def median_cut(cols, k):
    boxes = [list(cols)]
    while len(boxes) < k:
        boxes.sort(key=lambda b: -(len(b) if len(set(b)) > 1 else 0))
        b = boxes.pop(0)
        if len(set(b)) < 2: boxes.append(b); break
        rng = [max(c[i] for c in b) - min(c[i] for c in b) for i in range(3)]
        ch = rng.index(max(rng)); b.sort(key=lambda c: c[ch]); m = len(b) // 2
        boxes += [b[:m], b[m:]]
    return [tuple(sum(c[i] for c in b) // len(b) for i in range(3)) for b in boxes]

def nearest(p, pal):
    return min(range(len(pal)), key=lambda i: sum((p[k] - pal[i][k]) ** 2 for k in range(3)))

out = ['/* generated by tools/mkplanets.py from gfx/gyrussplanets.png: the planets of Gyruss as sprite data (do not edit) */',
       '#define GY_N %d' % len(PL), '#define GY_ROWS %d' % ROWS]
pals = []; words = []
for name, x0, x1, y0, y1 in PL:
    img = crop(x0, x1, y0, y1)
    if name == 'Saturn':                          # the ring (the diagonal x + y = 318 on the sheet, 3 pixels wide) is longer at the top right than at the bottom left: cut it to the same length around the planet
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                if abs(x + y - 318) <= 1 and ((x - 272.5) ** 2 + (y - 45) ** 2) ** 0.5 > 20.4: img[y - y0][x - x0] = BOX
    img = scale_to_width(img, 32)
    for y in range(len(img)):                     # isolated pixels (bits of the label text on the sheet) are dropped
        for x in range(len(img[0])):
            if opaque(img[y][x]) and not any(opaque(img[yy][xx]) for yy in range(max(0, y - 1), min(len(img), y + 2)) for xx in range(max(0, x - 1), min(len(img[0]), x + 2)) if (yy, xx) != (y, x)):
                img[y][x] = BG
    if len(img) > ROWS: img = img[(len(img) - ROWS) // 2:(len(img) - ROWS) // 2 + ROWS]
    ys = [y for y in range(len(img)) if any(opaque(p) for p in img[y])]; xs = [x for x in range(len(img[0])) if any(opaque(img[y][x]) for y in range(len(img)))]
    img = [r[xs[0]:xs[-1] + 1] for r in img[ys[0]:ys[-1] + 1]]
    h, w = len(img), len(img[0])
    allc = [p for r in img for p in r if opaque(p)]
    pal = median_cut(allc, 8)
    ox = 16 - w // 2; oy = ROWS // 2 - h // 2
    rows = [[0] * 32 for _ in range(ROWS)]
    for y in range(h):
        for x in range(w):
            if opaque(img[y][x]): rows[oy + y][ox + x] = 1 + nearest(img[y][x], pal)
    pals.append(pal)
    wl = []
    for r in rows:
        for half in range(2):
            a = b = c = d = 0
            for i in range(16):
                code = r[half * 16 + i]
                if code & 1: a |= 0x8000 >> i
                if code & 2: b |= 0x8000 >> i
                if code & 4: c |= 0x8000 >> i
                if code & 8: d |= 0x8000 >> i
            wl += [a, b, c, d]
    words.append(wl)
    print(name, w, 'x', h, 'colours', len(set(map(tuple, pal))), file=sys.stderr)
# procedural sprites (no source image): the moon, the Death Star and Endor, drawn here in 8 colours (the registers 17 .. 24) as spheres lit from the upper left, dithered (4 x 4 ordered)
import math
BAY = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5]
def sphere(R, ramp, shader):
    """shader(dx, dy, nx, ny, nz, lit) -> the brightness 0 .. 1 of the pixel; ramp = 8 colours (12 bit) dark to light"""
    rows = [[0] * 32 for _ in range(ROWS)]
    for y in range(ROWS):
        for x in range(32):
            dx = x - 15.5; dy = y - ROWS / 2 + 0.5
            if dx * dx + dy * dy > R * R: continue
            nx, ny = dx / R, dy / R; nz = math.sqrt(max(0.0, 1 - nx * nx - ny * ny))
            lit = max(0.0, nx * -0.5 + ny * -0.45 + nz * 0.74)
            v = shader(dx, dy, nx, ny, nz, lit)
            q = max(0.0, min(0.999, v)) * 7
            lvl = int(q) + (1 if (q - int(q)) * 16 > BAY[(y & 3) * 4 + (x & 3)] else 0)
            rows[y][x] = 1 + min(7, lvl)
    wl = []
    for r in rows:
        for half in range(2):
            a_ = b_ = c_ = d_ = 0
            for i in range(16):
                code = r[half * 16 + i]
                if code & 1: a_ |= 0x8000 >> i
                if code & 2: b_ |= 0x8000 >> i
                if code & 4: c_ |= 0x8000 >> i
                if code & 8: d_ |= 0x8000 >> i
            wl += [a_, b_, c_, d_]
    words.append(wl)
    pals.append([((g >> 8) * 17, (g >> 4 & 15) * 17, (g & 15) * 17) for g in ramp])

def noise(x, y, k=0): return (((int(x) * 73856093) ^ (int(y) * 19349663) ^ (k * 83492791)) & 255) / 255.0

CRATERS = [(-5, -6, 4.5), (4, -3, 3.2), (-8, 3, 3.0), (2, 6, 5.0), (8, 7, 2.2), (-2, -1, 2.0), (9, -8, 2.5), (-9, -4, 1.8), (-1, 10, 2.0), (6, 1, 1.6)]
def moon(dx, dy, nx, ny, nz, lit):
    alb = 0.9
    for cx, cy, cr in CRATERS:
        d = math.hypot(dx - cx, dy - cy)
        if d < cr * 0.82: alb = min(alb, 0.55)
        elif d < cr: alb = max(alb, 1.12)
    alb *= 0.94 + 0.12 * noise(dx * 2, dy * 2)
    return 0.06 + 0.94 * lit * alb
sphere(14.0, [0x111, 0x333, 0x555, 0x777, 0x999, 0xBBB, 0xDDD, 0xFFF], moon)

def deathstar(dx, dy, nx, ny, nz, lit):
    alb = 0.92 + 0.08 * noise(dx, dy, 3)
    # the equatorial trench: the equator seen slightly from above is the curve y = 0.12 * sqrt(1 - x^2) (in units of the radius)
    if abs(ny - 0.14 * math.sqrt(max(0.0, 1 - nx * nx))) < 0.045: alb *= 0.35
    # panel lines: a few latitudes and meridians, faint
    lat = math.asin(max(-1, min(1, ny))); lon = math.atan2(nx, nz)
    if abs((lat * 6 / math.pi) % 1.0 - 0.5) > 0.47 or abs((lon * 8 / math.pi) % 1.0 - 0.5) > 0.48: alb *= 0.8
    # the superlaser dish: a concave circle on the upper right, a rim and a dark floor lit from the other side
    cx, cy = 0.36, -0.40; dd = math.hypot(nx - cx, ny - cy)
    if dd < 0.27:
        if dd > 0.22: alb *= 1.25                            # the rim
        else:
            dl = max(0.0, -(nx - cx) * -0.5 - (ny - cy) * -0.45 + 0.4)
            return 0.05 + 0.5 * dl * (0.6 + 0.4 * (1 - dd / 0.22))   # the floor: lit on the side away from the light
        if dd < 0.05: return 1.0                             # the focus point of the laser
    return 0.07 + 0.93 * lit * alb
sphere(14.0, [0x112, 0x223, 0x445, 0x667, 0x889, 0xAAB, 0xCCD, 0xEEF], deathstar)

def endor(dx, dy, nx, ny, nz, lit):
    lat = math.asin(max(-1, min(1, ny))); lon = math.atan2(nx, nz)
    f = math.sin(lon * 3 + 1.2) + math.sin(lat * 5 + lon * 2) + 0.6 * math.sin(lon * 7 - lat * 3)
    alb = 0.62 + 0.10 * f + 0.12 * (noise(dx * 1.5, dy * 1.5, 9) - 0.5)       # forest: patches of darker and lighter green
    cl = math.sin(lon * 4 + lat * 6 + 0.5) + 0.7 * math.sin(lon * 9 - lat * 4)
    if cl > 1.05: alb = 1.0                                                # a few streaks of cloud
    return 0.05 + 0.95 * lit * alb
sphere(14.0, [0x010, 0x131, 0x252, 0x373, 0x4A4, 0x6C6, 0xAEA, 0xEFE], endor)
# the balloon of the C64 User's Guide (the sprite chapter): its 24 x 21 bit data, as it is, one colour (white) like the sprite on the C64
BALLOON = [(0, 127, 0), (1, 255, 192), (3, 255, 224), (3, 231, 224), (7, 217, 240), (7, 223, 240), (7, 217, 240), (3, 231, 224), (3, 255, 224), (3, 255, 224), (2, 255, 160),
           (1, 127, 64), (1, 62, 64), (0, 156, 128), (0, 156, 128), (0, 73, 0), (0, 73, 0), (0, 62, 0), (0, 62, 0), (0, 62, 0), (0, 28, 0)]
bl_pal = [0xFFF] * 8                                                    # one colour: white
bits = [[(BALLOON[y][x // 8] >> (7 - x % 8)) & 1 for x in range(24)] for y in range(21)]
rows = [[0] * 32 for _ in range(ROWS)]
oy = ROWS // 2 - 21 // 2; ox = 4
src = [[1 if bits[y][x] else 0 for x in range(24)] for y in range(21)]      # one colour, exactly the bits of the C64 data (the cut-out stays empty)
# the original size, 24 x 21 (the hardware has no sprite expansion), centred in the 32 pixel window
oy = ROWS // 2 - 21 // 2
for y in range(21):
    for x in range(24):
        rows[oy + y][4 + x] = src[y][x]
wl = []
for r in rows:
    for half in range(2):
        a_ = b_ = c_ = d_ = 0
        for i in range(16):
            code = r[half * 16 + i]
            if code & 1: a_ |= 0x8000 >> i
            if code & 2: b_ |= 0x8000 >> i
            if code & 4: c_ |= 0x8000 >> i
            if code & 8: d_ |= 0x8000 >> i
        wl += [a_, b_, c_, d_]
words.append(wl)
pals.append([((g >> 8) * 17, (g >> 4 & 15) * 17, (g & 15) * 17) for g in bl_pal])
words = words[len(PL) + 1:len(PL) + 4]; pals = pals[len(PL) + 1:len(PL) + 4]      # the Death Star, Endor and the balloon are kept (the moon and the planets of Gyruss are not used any more)
MOON = 0
out[1] = '#define GY_N %d' % len(words)
out.append('#define GY_FIXED %d                              /* the index of the first sprite that is not tinted by the palette: 0 = all of them (1 the Death Star, 2 Endor, 3 the balloon: the other sprites are gone) */' % MOON)
print('Death Star, Endor, balloon kept', file=sys.stderr)
out.append('static const unsigned short gyPal[GY_N][8] = {')
for pal in pals: out.append('\t{ ' + ', '.join('0x%04X' % (((r >> 4) << 8) | ((g >> 4) << 4) | (b >> 4)) for r, g, b in pal + [(0, 0, 0)] * (8 - len(pal))) + ' },')
out.append('};')
out.append('static const unsigned short gyWords[GY_N][GY_ROWS][8] = {')
for wl in words:
    out.append('\t{')
    for i in range(0, len(wl), 8): out.append('\t\t{ ' + ', '.join('0x%04X' % v for v in wl[i:i + 8]) + ' },')
    out.append('\t},')
out.append('};')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'gyruss_planets.h'), 'w').write('\n'.join(out) + '\n')
