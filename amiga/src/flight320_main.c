/* ---- the fast pipeline (68030 or better with fast RAM, chosen at run time): the CPU does everything in a work buffer in fast RAM (clear, plot, drip, contour points, digits: cached, 32 bit)
   and then copies the three finished planes into the chip RAM frame (about 24 KB of chip writes).  The blitter is not used.  Without fast RAM or on a 68000 / 68020 the blitter pipeline above runs. ---- */
#ifndef FORCE_PIPE
#define FORCE_PIPE (-1)                              /* -DFORCE_PIPE=0: always the blitter pipeline, 1: always the fast one (needs fast RAM), default: decide at run time */
#endif
volatile int fastPipe;                              /* 1 = fast pipeline (read through the debugger) */
static UBYTE *wkMem, *wp[3];                        /* the work planes in fast RAM (the same layout as in chip RAM: PLANE_ALLOC apart, a zero line in front) */
#define WK_BYTES ((3 * PLANE_ALLOC + 63) & ~31)

static int wkTop;                                   /* the first row of the work planes that may be non-zero */
static void ClearWork(void) {                       /* only the rows the last picture used */
	for (int k = 0; k < 3; k++) {
		ULONG *q = (ULONG *)(wp[k] + wkTop * PLANE_LINE), *e = (ULONG *)(wp[k] + PLANE_BYTES);
		do { q[0] = 0; q[1] = 0; q[2] = 0; q[3] = 0; q[4] = 0; q[5] = 0; q[6] = 0; q[7] = 0; q[8] = 0; q[9] = 0; q += 10; } while (q < e);
	}
}

static void DripWork(UBYTE *plane, int r0) {         /* plane := plane OR the row above, row after row (10 longs per row), from the highest ridge row down: what the blitter chain does */
	ULONG *q = (ULONG *)(plane + r0 * PLANE_LINE), *e = (ULONG *)(plane + PLANE_BYTES);
	do {
		q[0] |= q[-10]; q[1] |= q[-9]; q[2] |= q[-8]; q[3] |= q[-7]; q[4] |= q[-6];
		q[5] |= q[-5]; q[6] |= q[-4]; q[7] |= q[-3]; q[8] |= q[-2]; q[9] |= q[-1];
		q += 10;
	} while (q < e);
}

static void CopyToChip(UBYTE *dst, const UBYTE *src, int row) {      /* the rows from `row` (a multiple of 4: 160 bytes = 5 blocks of 32 bytes) of one plane into chip RAM */
	ULONG *d = (ULONG *)(dst + row * PLANE_LINE); const ULONG *s = (const ULONG *)(src + row * PLANE_LINE); int n = (PLANE_BYTES - row * PLANE_LINE) / 32;
	do {
		ULONG a = s[0], b = s[1], c = s[2], e = s[3], g = s[4], h = s[5], i = s[6], j = s[7];
		d[0] = a; d[1] = b; d[2] = c; d[3] = e; d[4] = g; d[5] = h; d[6] = i; d[7] = j;
		s += 8; d += 8;
	} while (--n);
}

