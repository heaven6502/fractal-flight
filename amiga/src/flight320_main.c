static void BagShuffle(UBYTE *bag, int from, int n, ULONG *rnd) {     /* Fisher-Yates on bag[from .. n-1] */
	for (int i = n - 1; i > from; i--) {
		*rnd = *rnd * 1664525UL + 1013904223UL;
		int j = from + (int)((UWORD)(*rnd >> 16) % (UWORD)(i - from + 1));
		UBYTE x = bag[i]; bag[i] = bag[j]; bag[j] = x;
	}
}
static void BagStart(UBYTE *bag, int n, int first, ULONG *rnd) {     /* the first round: the value shown now first, the others shuffled */
	for (int i = 0; i < n; i++) bag[i] = (UBYTE)i;
	bag[0] = (UBYTE)first; bag[first] = 0;
	BagShuffle(bag, 1, n, rnd);
}
static int BagNext(UBYTE *bag, int n, int *used, int last, ULONG *rnd) {
	if (*used >= n) {                                    /* a new round: shuffled, but not starting with the value that was shown last */
		for (int i = 0; i < n; i++) bag[i] = (UBYTE)i;
		BagShuffle(bag, 0, n, rnd);
		if (bag[0] == last) { bag[0] = bag[n - 1]; bag[n - 1] = (UBYTE)last; }
		*used = 0;
	}
	return bag[(*used)++];
}
