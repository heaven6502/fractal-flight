/* ---- the depth bands: three ground colours, near (F) / middle (E) / far (C); a pixel's colour index is the set of band silhouettes it lies below (bit 0 = near, 1 = middle, 2 = far):
   it belongs to the nearest band in the set: 1 3 5 7 = near, 2 6 = middle, 4 = far, 0 = sky.  The colours follow the camera through the grid cell like the game's (it indexes luminance tables with the
   fraction of the cell): the depth of a band drifts nearer as the camera flies and the colour with it, so the step when the fan jumps one row is a small one. ---- */
extern int fFwdFrac, fFarPhase;
#define GROUND_NEAR 0x0A63                           /* the colour of the ground at the camera (a range of 3 levels: neighbouring bands differ by one step per channel) */
#define GROUND_FAR  0x0D96                           /* ... at the distance of the haze */
#define HAZE_DEPTH  11000                            /* game units */
#define CELL_DEPTH  2040                             /* the depth of one row of the fan */
static UWORD BandColour(int depth) {
	int t = depth * 256 / HAZE_DEPTH, v = 0;
	if (t > 256) t = 256;
	for (int sh = 8; sh >= 0; sh -= 4) {
		int a = (GROUND_NEAR >> sh) & 15, f = (GROUND_FAR >> sh) & 15;
		v |= (a + (((f - a) * t) >> 8)) << sh;
	}
	return (UWORD)v;
}
