/* ---- keyboard (the system is taken over, so the keyboard is polled in the vertical blank): cursor keys fly like the joystick (as on the ST), Esc / Space quit ---- */
static volatile UBYTE kbUp, kbDown, kbLeft, kbRight, kbQuit;
static void KbPoll(void) {
	volatile UBYTE *ciaa = (volatile UBYTE *)0xBFE001;       /* CIA-A: SDR = +0xC00 (0xBFEC01), ICR = +0xD00, CRA = +0xE00 */
	if (ciaa[0xD00] & 0x08) {                                /* a key byte arrived in the serial register (reading ICR clears the flag) */
		UBYTE s = ciaa[0xC00], k = (UBYTE)~((s >> 1) | (s << 7)), down = !(k & 0x80);
		ciaa[0xE00] |= 0x40;                                 /* handshake: SP line output for at least 85 us (3 raster lines) */
		for (int n = 0; n < 3; n++) { UBYTE l = (UBYTE)(custom->vhposr >> 8); while ((UBYTE)(custom->vhposr >> 8) == l) ; }
		ciaa[0xE00] &= ~0x40;
		switch (k & 0x7F) {
		case 0x4C: kbUp = down; break;
		case 0x4D: kbDown = down; break;
		case 0x4F: kbLeft = down; break;
		case 0x4E: kbRight = down; break;
		case 0x45: case 0x40: if (down) kbQuit = 1; break;   /* Esc, Space */
		case 0x08: if (down) gHaze = (UBYTE)((gHaze + 1) & 3); break;              /* key 8: the haze over the sun / planet sprites (their colours towards the sky) */
		case 0x09: if (down && !gGenWant && !gTrans) { UBYTE nh = (UBYTE)(gHalf >= SUN_SHAPES - 1 ? 0 : gHalf + 1); if (nh >= SH_GEN) { gNextHalf = nh; gGenSeed = (unsigned long)frameCounter * 40503UL + 7; gManualGen = 1; gGenWant = 1; } else gHalf = nh; } break;      /* key 9: the whole sun / half lit / quarter lit / moon, Death Star, Endor, balloon / the procedural planets (a new one each time) */
		case 0x0A: if (down) gWobble ^= 1; break;                          /* key 0: the heat shimmer of the sun on / off */
		case 0x01: case 0x02: case 0x03: case 0x04: if (down) gPal = (UBYTE)((k & 0x7F) - 1); break;    /* keys 1 .. 4: the palette */
		case 0x05: if (down) { gPal = (UBYTE)(gPal + 1 >= NPAL ? 0 : gPal + 1); if (gPal >= 8) PalGen(&palettes[gPal], (unsigned long)frameCounter * 2654435761UL + gPal); } break;                                          /* key 5: the next of the eight palettes (5 .. 8 are only reached this way, or by the autopilot) */
		}
	}
}
