	gx = bunkX[b]; gr = PIC_H - 1 - bunkY[b];
	if (gx < 0 || gx > 319 || gr < 0 || gr > PIC_H - 10) return 0;
	tx = 160 - 15 + ((LzRnd() * 31) >> 8);
