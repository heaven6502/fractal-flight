static u16 D3(unsigned short c) {                       /* a 12 bit colour (4 bit channels) as the 3 bit colour of the plain ST */
	int r = ((c >> 8) & 15) + 1 >> 1, g = ((c >> 4) & 15) + 1 >> 1, b = (c & 15) + 1 >> 1;
	if (r > 7) r = 7; if (g > 7) g = 7; if (b > 7) b = 7;
	return (u16)(r << 8 | g << 4 | b);
}
static void PalGenSt(int n, unsigned long seed) {       /* a procedural palette into the entry n */
	struct PalEnt e;
	PalGen(&e, seed);
	palettes[n][0] = D3(e.sky); palettes[n][1] = D3(e.nearC); palettes[n][2] = D3(e.mid); palettes[n][3] = D3(e.farC);
	palettes[n][4] = D3(e.farC); palettes[n][5] = D3(e.bar);
	palettes[n][6] = D3(e.halo); palettes[n][7] = D3(e.body); palettes[n][8] = D3(e.core);
}
static void ApplyPalette(int n) {
	const u16 *c = palettes[n];
	palette[8] = c[0];
	palette[9] = palette[11] = palette[13] = palette[15] = c[1];
	palette[10] = palette[14] = c[2];
	palette[12] = c[3];
	palette[0] = c[4]; palette[1] = 0;                  /* the border; the scroller bar is black */
}
