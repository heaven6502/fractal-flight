static const u8 font35[10][5] = {      /* 3 x 5 digits, bit 2 = left */
	{7,5,5,5,7}, {2,6,2,2,7}, {7,1,7,4,7}, {7,1,7,1,7}, {5,5,7,1,1}, {7,4,7,1,7}, {7,4,7,5,7}, {7,1,1,1,1}, {7,5,7,5,7}, {7,5,7,1,7}
};
static void DrawFps(u8 *s, int value) {                /* the picture rate x 10: 4 digits at x = 8, 16, 24, 32 (every digit is a byte of the screen line), every font pixel 2 x 2 screen pixels, the near colour (planes 0 and 1), the picture under the digits stays */
	static const u8 ex[8] = { 0, 3, 12, 15, 48, 51, 60, 63 };       /* 3 font bits -> 6 pixels */
	int d;
	for (d = 0; d < 4; d++) {
		int div = d == 0 ? 1000 : d == 1 ? 100 : d == 2 ? 10 : 1, n = (value / div) % 10, x = 8 + d * 8, r;
		const u8 *f = font35[n];
		int sh = (x & 8) ? 0 : 8;                       /* the low or the high byte of the word */
		u16 *w = (u16 *)(s + 6 * 160 + (x >> 4) * 8);
		if (value < div && d != 3) continue;           /* blank leading zeros */
		for (r = 0; r < 5; r++, w += 160 / 2 * 2) {      /* two lines per font row */
			u16 m = (u16)((ex[f[r]] << 2) << sh);
			w[0] |= m; w[1] |= m;
			w[80] |= m; w[81] |= m;
		}
	}
}
