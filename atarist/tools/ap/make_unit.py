"""make_unit.py - builds ap_unit.asm / ap_unit.xex: the autopilot routine of flight800_far_pm_iron.asm, copied verbatim from the Atari source, in a test harness for ap_check.py"""
import subprocess, os
HERE = os.path.dirname(os.path.abspath(__file__))
src = open(r"C:/coding/Atari/rof/flight800/flight800_far_pm_iron.asm").read().split("\n")
def find(prefix):
    for i, l in enumerate(src):
        if l.startswith(prefix): return i
    raise SystemExit("not found " + prefix)
core = src[find("TRIG0       = $D010"):find("; day cycle of the demo flight")]
tables = src[find("; phase table: mode, ticks"):find("ap_stick") + 1]
asm = """; ap_unit.asm - generated by make_unit.py: the autopilot of flight800_far_pm_iron.asm (verbatim) in a test harness: the host writes the inputs, sets GO and reads the results
CH          = $02FC
PORTA       = $D300
NV          = 55
VXH         = $1180
VZH         = $1200
VH          = $12C0
VFLAG       = $1400
f_alt       = $289F
f_thrust    = $2887
m061D       = $061D
m065F       = $065F
GO          = $0600                 ; 1 = run the autopilot once
OUT         = $0610                 ; results: stick, ap_l, ap_r, ap_t, ap_ph, thrust, CH

            org $2000
main        lda GO
            beq main
            jsr autopilot
            sta OUT
            lda ap_l
            sta OUT+1
            lda ap_r
            sta OUT+2
            lda ap_t
            sta OUT+3
            lda ap_ph
            sta OUT+4
            lda CH                  ; the key the autopilot pressed: applied like the game's "keys" does (ky_up / ky_dn, with ky_cancel)
            cmp #$06
            bne k_dn
            jsr ky_cancel
            lda f_thrust
            cmp #100
            bcs k_end
            inc f_thrust
            jmp k_end
k_dn        cmp #$0E
            bne k_end
            jsr ky_cancel
            lda f_thrust
            beq k_end
            dec f_thrust
k_end       lda f_thrust
            sta OUT+5
            lda CH
            sta OUT+6
            lda #$FF
            sta CH
            lda #0
            sta GO
            jmp main
ky_cancel   lda m065F
            bne kc_end
            lda #$FF
            sta m065F
            lda #$1E
            sta f_thrust
kc_end      rts

day_tick    rts
day_set     rts
ap_day      .byte 0

""" + "\n".join(core) + "\n" + "\n".join(tables) + "\n\n            run main\n"
open(os.path.join(HERE, "ap_unit.asm"), "w").write(asm)
subprocess.check_call([r"C:/coding/3dengine/mads.exe", "ap_unit.asm", "-o:ap_unit.xex", "-l:ap_unit.lst"], cwd=HERE, stdout=subprocess.DEVNULL)
print("built ap_unit.xex")
