"""mkhackl.py - src/st_hackl.s (the MOD replay of the STE flight) from music/mod/HACKL00I.s, "Hacking Lance" v13 by Paulo Simoes (10 May 2013, "Enjoy it and use it if you want"),
which is a rework of the replay routine of Lance / Marten Ronge (1993).  The program HACKL00I.s is a complete demo (own system takeover, video, MFP, disk and key handling); only the replay
core is taken here, with a small glue (ModInit / ModVbl / ModStop, below) in place of the program's main loop:
  - the configuration words (12.5 kHz, normal play: no trash buffers, volume control and BPM detected from the module)
  - init_code (patches the generated mixer code for the replay frequency)
  - qinitSTEdma (the DMA sound chip and the Microwire volume / tone registers)
  - qmalloc (a bump allocator over a block we give it) and q_handle_bpm
  - mt_init, mt_Paula, mt_mixer, mt_music, mt_end and the tables (everything from 'mt_init' to the end of the file)
usage: python tools/mkhackl.py       (then src/st_hackl.s is assembled by vasm with -devpac, see the Makefile)"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
src = open(os.path.join(ROOT, "music", "mod", "HACKL00I.s"), encoding="latin-1").read().split("\n")


def lines(a, b):                                   # 1 based, inclusive
    return "\n".join(src[a - 1:b]) + "\n"


def find(prefix, start=1):
    for i in range(start - 1, len(src)):
        if src[i].startswith(prefix):
            return i + 1
    raise SystemExit("not found: " + prefix)


init_code = find("init_code:")
lmod_banner = find("* PROC: LMOD") - 1
qinitdma = find("qinitSTEdma:")
qinitdma_end = find("*\t$FFFF8901.w")                 # the comment block after qinitSTEdma / inidmaw
qmalloc = find("qmalloc:")
qmfree_end = find("qreturnmem:") - 1
handle_bpm = find("q_handle_bpm:")
handle_bpm_end = find("l_handle_bpm_9") + 3          # l_handle_bpm_9: bsr mt_music / bsr mt_mixer / rts
core = find("*\tmt_init\t\tMOD preparation procedure") - 2

glue_top = """; st_hackl.s - generated by tools/mkhackl.py from music/mod/HACKL00I.s (Hacking Lance v13, Paulo Simoes 2013, after Lance / Marten Ronge 1993): the MOD replay of the STE flight.
; Devpac syntax: assemble with  vasmm68k_mot -devpac -Felf -m68000.  Position independent, the variables are in the code section, the mixer code is generated into the block given to ModInit.
	section	.text,code
	xdef	ModInit
	xdef	ModVbl
	xdef	ModStop
	xdef	modFrames
	xdef	zfreememsize

*** the configuration of the flight (the original program has these as dc.w at the top)
zreplayfreq	dc.w	$0001		12.5 KHz
z_autovoldetect	dc.w	$0001		volume control only when the module uses it
z_volume_active	dc.w	$0001
z_trash_idx	dc.w	2		normal play (no trash buffers)
z_improve_avg	dc.w	$0001
z_octave3_cheat	dc.w	$0000
z_read_skips	dc.w	0
z_global_volume	dc.w	$FFFF
z_autobpmdetect	dc.w	$0001		BPM only when the module uses it
z_bpm_active	dc.w	$0001
zs_amiga_freq	dc.l	7093790		PAL
	even

"""

glue_bottom = """

***************************************************************************
* the glue: the C interface
***************************************************************************
* int ModInit(const unsigned char *mod, unsigned long modlen, unsigned char *arena, unsigned long arenasize)
*	copies the module into the arena (with the loop space the replay needs behind it), prepares the replay (generates the mixer code into the arena), starts nothing yet.
*	returns 0 = ok, 1 = arena too small
ModInit:
	movem.l	d2-d7/a2-a6,-(sp)		44 bytes: the arguments are at 48 .. 60(sp)
	lea	zpfreemem(pc),a0
	move.l	56(sp),(a0)			the arena
	lea	zfreememsize(pc),a0
	move.l	60(sp),(a0)
	bsr	qinitSTEdma			DMA off, Microwire volume / tone
	move.l	52(sp),d0			module length
	add.l	#484+31*2*664,d0		484 bytes + 31 samples * 2 * 664 bytes (like the original LMOD)
	bsr	qmalloc				A0 = the block, D0 = remaining bytes
	tst.l	d0
	bmi.s	lmodinit_fail
	move.l	a0,a2				the module copy (mt_init moves it to the top of the block)
	move.l	48(sp),a1
	move.l	52(sp),d1
	subq.l	#1,d1
lmodinit_copy
	move.b	(a1)+,(a2)+
	subq.l	#1,d1
	bpl.s	lmodinit_copy
	move.l	52(sp),d0			module length
	bsr	mt_init
	lea	mt_trash_active(pc),a0
	sf	(a0)
	lea	mt_trash_rd_idx(pc),a0
	move	#1,(a0)				read index 1 (like PLAY_IT00)
	lea	modFrames(pc),a0
	clr.l	(a0)
	moveq	#0,d0
	bra.s	lmodinit_e
lmodinit_fail
	moveq	#1,d0
lmodinit_e
	movem.l	(sp)+,d2-d7/a2-a6
	rts

* void ModVbl(void)    once per vertical blank, first thing: the DMA registers for the buffer that was mixed last time, then the module and the mixing of the next buffer
ModVbl:
	movem.l	d0-d7/a0-a6,-(sp)
	lea	mt_trash_rd_idx(pc),a0
	move.l	(a0),d0
	swap	d0
	move.l	d0,(a0)				switch buffers
	bsr	mt_Paula
	bsr	q_handle_bpm			mt_music + mt_mixer (and the BPM timers)
	lea	modFrames(pc),a0
	addq.l	#1,(a0)
	movem.l	(sp)+,d0-d7/a0-a6
	rts

* void ModStop(void)
ModStop:
	movem.l	d0-d7/a0-a6,-(sp)
	bsr	mt_end
	clr.b	$FFFF8901.w			DMA off
	movem.l	(sp)+,d0-d7/a0-a6
	rts

modFrames	dc.l	0			vertical blanks since ModInit (the music's clock)

zpfreemem	ds.l	1
zfreememsize	ds.l	1
zpreturnmem	ds.l	1
zaboveSTE	dc.b	0			not a Falcon / CT60 (qinitSTEdma sets the Microwire registers)
zSTE		dc.b	1
	even
"""

out = glue_top
out += "*** init_code: patches the mixer code for the replay frequency (HACKL00I.s lines %d - %d)\n" % (init_code, lmod_banner)
out += lines(init_code, lmod_banner)
out += "\n*** the STE DMA sound setup (lines %d - %d)\n" % (qinitdma, qinitdma_end - 1)
out += lines(qinitdma, qinitdma_end - 1)
out += "\n*** memory: a bump allocator over the arena (lines %d - %d)\n" % (qmalloc, qmfree_end)
out += lines(qmalloc, qmfree_end)
out += "\n*** BPM handling (lines %d - %d)\n" % (handle_bpm, handle_bpm_end)
out += lines(handle_bpm, handle_bpm_end)
out += "\n*** the replay core: mt_init, mt_Paula, mt_mixer, mt_music, mt_end and the tables (lines %d - %d)\n" % (core, len(src))
out += lines(core, len(src))
out += glue_bottom
open(os.path.join(ROOT, "src", "st_hackl.s"), "w", encoding="latin-1", newline="\n").write(out)
print("src/st_hackl.s written (%d lines)" % out.count("\n"), "core from line", core)
