"""mklogo.py [image] - a 16 colour 320 x 200 Atari ST low resolution picture (the intro logo) from an image:
  gfx/st4/<name>_st16.png   the picture with the ST colours (what the ST shows)
  gfx/st4/<name>_st16.pal   the 16 ST palette entries (0RGB, 3 bits per channel)
  src/logo_data.c           logoPal[16] and logoImg[16000] (200 lines x 20 groups x 4 bitplane words, the ST's interleaved low resolution format)
The image is scaled to cover 320 x 200 (the middle part when it is taller), the 16 colours are chosen by median cut in the 3 bit ST colour space and the picture is dithered with an ordered Bayer 8 x 8 matrix.
usage: python tools/gfx/mklogo.py [gfx/Desire_Logo_rock_001.png]"""
import os, sys
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "gfx", "Desire_Logo_rock_001.png")
name = os.path.splitext(os.path.basename(src))[0]
W, H = 320, 200
BAYER8 = np.array([[0, 32, 8, 40, 2, 34, 10, 42], [48, 16, 56, 24, 50, 18, 58, 26], [12, 44, 4, 36, 14, 46, 6, 38], [60, 28, 52, 20, 62, 30, 54, 22],
                   [3, 35, 11, 43, 1, 33, 9, 41], [51, 19, 59, 27, 49, 17, 57, 25], [15, 47, 7, 39, 13, 45, 5, 37], [63, 31, 55, 23, 61, 29, 53, 21]], dtype=float)

im = Image.open(src).convert("RGB")
colors = im.getcolors(1 << 20)
exact = im.width == W and im.height <= H and len(colors) <= 16     # already a 320 wide picture with at most 16 colours (like gfx/st4/desire_logo.png): no scaling, no dithering,
if exact:                                                          # centred on a screen filled with its most frequent colour (the background)
    bg = max(colors)[1]
    canvas = Image.new("RGB", (W, H), bg)
    canvas.paste(im, (0, (H - im.height) // 2))
    im = canvas
else:
    scale = max(W / im.width, H / im.height)                       # cover
    nw, nh = round(im.width * scale), round(im.height * scale)
    im = im.resize((nw, nh), Image.LANCZOS)
    left = (nw - W) // 2
    top = (nh - H) // 2
    if len(sys.argv) > 2:
        top = int(sys.argv[2])
    im = im.crop((left, top, left + W, top + H))

# the 16 colours: median cut on the picture reduced to the 3 bit colours of the ST
st3 = im.point(lambda v: round(v * 7 / 255) * 255 // 7)
q = st3.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
pal = q.getpalette()[:48]
hist = q.histogram()
cols = [tuple(round(pal[i * 3 + c] * 7 / 255) for c in range(3)) for i in range(16) if hist[i] > 0]      # only the colours the picture uses
cols = sorted(set(cols), key=lambda c: 0.3 * c[0] + 0.59 * c[1] + 0.11 * c[2])
while len(cols) < 16:
    cols.append(cols[-1])
pc = np.array([[c * 255 / 7 for c in col] for col in cols], dtype=float)         # palette in 0..255

# ordered dithering: add the Bayer threshold (about one ST colour step, 255 / 7 = 36) to the pixel, then the nearest palette colour
px = np.asarray(im, dtype=float)
thr = (BAYER8[np.arange(H)[:, None] % 8, np.arange(W)[None, :] % 8] + 0.5) / 64.0 - 0.5
dith = px + thr[:, :, None] * 36.0 * (0.0 if exact else 0.85)
d2 = ((dith[:, :, None, :] - pc[None, None, :, :]) ** 2).sum(axis=3)
idx = d2.argmin(axis=2)                                        # H x W colour numbers 0 .. 15

prev = Image.fromarray(pc[idx].astype(np.uint8), "RGB")
outdir = os.path.join(ROOT, "gfx", "st4")
os.makedirs(outdir, exist_ok=True)
prev.save(os.path.join(outdir, name + "_st16.png"))
palw = [(c[0] << 8) | (c[1] << 4) | c[2] for c in cols]
open(os.path.join(outdir, name + "_st16.pal"), "w").write("; %s: the 16 ST colours of the 320 x 200 intro picture (0RGB, 3 bits per channel, darkest first)\n\tdc.w %s\n" % (os.path.basename(src), ", ".join("$%04X" % c for c in palw)))

# the STE palette: the same colour numbers, but the true colours of the picture with 4 bits per channel (the mean of the picture pixels of every colour number; the ST palette above has 3 bits)
pal4 = []
for k in range(16):
    sel = idx == k
    mean = px[sel].mean(axis=0) if sel.any() else pc[k]
    pal4.append(tuple(int(round(v * 15 / 255)) for v in mean))
pal4w = [(c[0] << 8) | (c[1] << 4) | c[2] for c in pal4]
open(os.path.join(outdir, name + "_st16.pal"), "a").write("; the STE palette (4 bits per channel, plain 0RGB nibbles: the program turns them into the STE register format)\n\tdc.w %s\n" % ", ".join("$%04X" % c for c in pal4w))

# the ST's interleaved low resolution format: per line 20 groups of 16 pixels, every group = 4 words (plane 0 .. 3, bit 15 = the leftmost pixel)
words = []
for y in range(H):
    for g in range(20):
        for p in range(4):
            w = 0
            for k in range(16):
                w = (w << 1) | ((int(idx[y, g * 16 + k]) >> p) & 1)
            words.append(w)
lines = ["/* logo_data.c - generated by tools/gfx/mklogo.py from %s: the intro picture, 320 x 200, 16 colours (3 bit ST colours), ordered dithered; the ST's interleaved low resolution screen format */" % os.path.basename(src),
         "const unsigned short logoPal[16] = { %s };" % ", ".join("0x%04X" % c for c in palw),
         "const unsigned short logoPal4[16] = { %s };      /* the same colour numbers with 4 bits per channel (plain 0RGB nibbles) for an STE */" % ", ".join("0x%04X" % c for c in pal4w),
         "const unsigned short logoImg[16000] = {"]
for i in range(0, len(words), 16):
    lines.append("\t" + ",".join("0x%04X" % w for w in words[i:i + 16]) + ",")
lines.append("};")
open(os.path.join(ROOT, "src", "logo_data.c"), "w").write("\n".join(lines) + "\n")
print("src/logo_data.c written; ST palette:", " ".join("%03X" % c for c in palw))
print("STE palette:", " ".join("%03X" % c for c in pal4w))
