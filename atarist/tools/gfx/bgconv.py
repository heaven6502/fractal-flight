"""bgconv.py - source image -> the 4 colour background of the flight (320 x 150, planes 2 and 3).  convert(path, style, crop) returns (rows, palette, preview):
  rows     150 lists of 320 colour numbers 0 .. 3 (0 = the darkest colour)
  palette  the 4 ST colours 0RGB (3 bits per channel), darkest first
  preview  a PIL image with the ST colours
style: "flat" (median cut, no dither), "ordered" (Bayer 8 x 8 on the brightness, the palette spread over the brightness range of the image), "fs" (Floyd-Steinberg).
crop: rows cut off the top of the image scaled to 320 pixels wide; "mid" = the 150 rows in the middle; default 0."""
from PIL import Image
W, H = 320, 150
BAYER8 = [[0, 32, 8, 40, 2, 34, 10, 42], [48, 16, 56, 24, 50, 18, 58, 26], [12, 44, 4, 36, 14, 46, 6, 38], [60, 28, 52, 20, 62, 30, 54, 22],
          [3, 35, 11, 43, 1, 33, 9, 41], [51, 19, 59, 27, 49, 17, 57, 25], [15, 47, 7, 39, 13, 45, 5, 37], [63, 31, 55, 23, 61, 29, 53, 21]]


def scaled_height(path):
    im = Image.open(path)
    return round(im.height * W / im.width)


def load(path, crop=0):
    im = Image.open(path).convert("RGB")
    h2 = round(im.height * W / im.width)
    im = im.resize((W, h2), Image.LANCZOS)
    top = max(0, (h2 - H) // 2) if crop == "mid" else int(crop)
    im = im.crop((0, top, W, top + H))
    if im.height < H:                                            # too short: repeat the last row
        full = Image.new("RGB", (W, H))
        full.paste(im, (0, 0))
        for y in range(im.height, H):
            full.paste(im.crop((0, im.height - 1, W, im.height)), (0, y))
        im = full
    return im


def convert(path, style="ordered", crop=0):
    im = load(path, crop)
    im3 = im.point(lambda v: round(v * 7 / 255) * 255 // 7)       # what the ST can show: 3 bits per channel
    q = im3.quantize(colors=4, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.FLOYDSTEINBERG if style == "fs" else Image.Dither.NONE)
    pal = q.getpalette()[:12]
    cols = [tuple(round(pal[i * 3 + c] * 7 / 255) for c in range(3)) for i in range(4)]
    order = sorted(range(4), key=lambda i: 0.3 * cols[i][0] + 0.59 * cols[i][1] + 0.11 * cols[i][2])
    if style == "ordered":                                       # a palette spread over the brightness range (quantiles), so that the dither steps are even
        px = sorted((0.3 * r + 0.59 * g + 0.11 * b, (r, g, b)) for r, g, b in im3.getdata())
        lo, hi = px[int(0.01 * (len(px) - 1))][0], px[int(0.997 * (len(px) - 1))][0]
        cols = []
        for k in range(4):                                       # 4 brightness levels spread evenly between the dark end and the bright end of the image
            t = lo + (hi - lo) * k / 3.0
            near = sorted(px, key=lambda p: abs(p[0] - t))[:60]
            cols.append(tuple(round(sum(p[1][c] for p in near) / len(near) * 7 / 255) for c in range(3)))
        order = list(range(4))
    pc = [tuple(c * 255 // 7 for c in cols[order[i]]) for i in range(4)]
    lum = [0.3 * r + 0.59 * g + 0.11 * b for r, g, b in pc]
    if style == "ordered":
        spread = max(1.0, (lum[3] - lum[0]) / 3.0)
        rows = []
        for y in range(H):
            row = []
            for x in range(W):
                r, g, b = im.getpixel((x, y))
                l = 0.3 * r + 0.59 * g + 0.11 * b + ((BAYER8[y & 7][x & 7] + 0.5) / 64.0 - 0.5) * spread * 1.2
                row.append(min(range(4), key=lambda i: abs(lum[i] - l)))
            rows.append(row)
    else:
        remap = {old: new for new, old in enumerate(order)}
        rows = [[remap[q.getpixel((x, y))] for x in range(W)] for y in range(H)]
    palette = [(cols[i][0] << 8) | (cols[i][1] << 4) | cols[i][2] for i in order]
    pv = Image.new("RGB", (W, H))
    for y in range(H):
        for x in range(W):
            pv.putpixel((x, y), pc[rows[y][x]])
    return rows, palette, pv


GROUND = 0x432                                                   # the mountain colour: Mars brown (the same for every background)


def ground_colour(palette):
    return GROUND


def planar_c(rows, palette, name):
    """the C source of src/sky_data.c"""
    out = ["/* sky_data.c - generated by tools/gfx/gen_bg.py from %s: the background image of the flight (planes 2 and 3 of the picture lines, 20 groups of 16 pixels), and its 4 ST colours */" % name,
           "const unsigned short skyPal[4] = { 0x%04X, 0x%04X, 0x%04X, 0x%04X };" % tuple(palette),
           "const unsigned short skyGround = 0x%04X;                      /* the mountain colour that stands out best from these 4 */" % ground_colour(palette),
           "const unsigned short skyBg[150][20][2] = {"]
    for y in range(H):
        row = []
        for g in range(20):
            p2 = p3 = 0
            for k in range(16):
                c = rows[y][g * 16 + k]
                p2 = p2 << 1 | (c & 1)
                p3 = p3 << 1 | (c >> 1)
            row.append("{0x%04X,0x%04X}" % (p2, p3))
        out.append("\t{" + ",".join(row) + "},")
    out.append("};")
    return "\n".join(out) + "\n"
