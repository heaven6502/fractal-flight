"""gen_sky.py - the background image of the flight: 320 x 150 pixels, 4 colours (the planes 2 and 3 of the ST screen), a Mars like sunset with a ringed planet and moons.
Writes src/sky_data.c (const unsigned short skyBg[150][20][2] = plane 2 word, plane 3 word of every 16 pixel group) and tools/gfx/sky_preview.png.
Colour numbers b: 0 dark space, 1 blue, 2 butterscotch, 3 pale (sun, planet rings, moons).  usage: python tools/gfx/gen_sky.py"""
import math, random, os
from PIL import Image
W, H = 320, 150
PAL = [(0x00, 0x00, 0x24), (0x24, 0x48, 0x90), (0xD8, 0x90, 0x60), (0xFF, 0xF0, 0xD0)]      # preview colours (the ST palette is set in flight_st.c)
rnd = random.Random(61)
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
img = [[0] * W for _ in range(H)]

def dither(v, x, y):                                    # v = 0 .. 3 (float): the nearest two colours with an ordered dither
    lo = int(v)
    if lo >= 3: return 3
    return lo + (1 if (v - lo) * 16 > BAYER[y & 3][x & 3] else 0)

HORIZON = 100
for y in range(H):
    for x in range(W):
        t = y / HORIZON if y < HORIZON else 1.0
        img[y][x] = dither(min(2.0, t * 2.05), x, y)    # space -> blue -> butterscotch at the horizon
# stars in the dark part
for _ in range(70):
    x, y = rnd.randrange(W), rnd.randrange(0, 52)
    if img[y][x] <= 1: img[y][x] = 3
def put(x, y, c):
    if 0 <= x < W and 0 <= y < H: img[y][x] = c
# the sun low at the horizon, with a blue glow
SX, SY = 98, 99
for y in range(H):
    for x in range(W):
        d = math.hypot((x - SX) * 0.8, y - SY)
        if d < 7.5: img[y][x] = 3
        elif d < 30 and img[y][x] == 2:
            if (1 - (d - 7.5) / 22.5) * 16 > BAYER[y & 3][x & 3]: img[y][x] = 1
        elif d < 30 and img[y][x] == 1 and d < 14:
            if (1 - (d - 7.5) / 6.5) * 16 > BAYER[(y + 2) & 3][(x + 2) & 3]: img[y][x] = 3 if d < 10 else 1
# the ringed planet
PX, PY, PR = 238, 46, 25
ang = math.radians(-18)
def ring_val(x, y):                                       # returns (r2 of the ring ellipse, side)  side < 0: behind the planet
    dx, dy = x - PX, y - PY
    rx = dx * math.cos(ang) + dy * math.sin(ang)
    ry = -dx * math.sin(ang) + dy * math.cos(ang)
    return (rx / 58.0) ** 2 + (ry / 13.0) ** 2, ry
for y in range(H):
    for x in range(W):
        d = math.hypot(x - PX, y - PY)
        r2, ry = ring_val(x, y)
        in_ring = 0.50 < r2 < 1.0
        if in_ring and ry < 0 and d >= PR:                    # the far half of the ring
            img[y][x] = 3 if r2 > 0.78 else 2
for y in range(H):
    for x in range(W):
        d = math.hypot(x - PX, y - PY)
        if d < PR:
            band = math.sin((y - PY) * 0.55) * 0.5 + 0.5      # gas bands
            lit = (PX - x) / PR * 0.7 + 0.35 - (y - PY) / PR * 0.15       # light from the left
            v = 1.0 + lit * 2.0 + (band - 0.5) * 0.9
            img[y][x] = dither(max(0.0, min(3.0, v)), x, y)
for y in range(H):
    for x in range(W):
        d = math.hypot(x - PX, y - PY)
        r2, ry = ring_val(x, y)
        if 0.50 < r2 < 1.0 and ry >= 0:                         # the near half of the ring, in front of the planet
            img[y][x] = 3 if r2 > 0.78 else 2 if (x + y) % 2 == 0 else 3
# moons
for (mx, my, mr, shade) in ((46, 30, 9, 1), (160, 18, 4, 0), (186, 70, 3, 0)):
    for y in range(my - mr - 2, my + mr + 3):
        for x in range(mx - mr - 2, mx + mr + 3):
            if math.hypot(x - mx, y - my) < mr:
                c = 3
                if shade and math.hypot(x - (mx + 4), y - (my - 2)) < mr - 1 and (x + y) % 2 == 0: c = 1       # a crescent
                put(x, y, c)
os.makedirs(os.path.join(os.path.dirname(__file__)), exist_ok=True)
pv = Image.new("RGB", (W, H))
for y in range(H):
    for x in range(W): pv.putpixel((x, y), PAL[img[y][x]])
pv.resize((W * 2, H * 2), Image.NEAREST).save(os.path.join(os.path.dirname(__file__), "sky_preview.png"))
# the planar data: per line 20 groups x (plane 2 word, plane 3 word); colour b = bit 0 -> plane 2, bit 1 -> plane 3
out = ["/* sky_data.c - generated by tools/gfx/gen_sky.py: the background image of the flight (planes 2 and 3 of the picture lines, 20 groups of 16 pixels) */",
       "const unsigned short skyBg[150][20][2] = {"]
for y in range(H):
    row = []
    for g in range(20):
        p2 = p3 = 0
        for k in range(16):
            c = img[y][g * 16 + k]
            p2 = p2 << 1 | (c & 1)
            p3 = p3 << 1 | (c >> 1)
        row.append("{0x%04X,0x%04X}" % (p2, p3))
    out.append("\t{" + ",".join(row) + "},")
out.append("};")
open(os.path.join(os.path.dirname(__file__), "..", "..", "src", "sky_data.c"), "w").write("\n".join(out) + "\n")
print("sky_data.c written")
