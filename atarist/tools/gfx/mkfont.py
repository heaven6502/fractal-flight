"""mkfont.py - gfx/Antic.chr (512 bytes: the 64 character 8 x 8 set of the Atari 8 bit ANTIC, in screen code order = ATASCII 32 .. 95: space ! " # ... 0-9 : ; < = > ? @ A-Z [ backslash ] ^ _)
into src/font_antic.c (const unsigned char fontAntic[64][8], bit 7 = the left pixel) for the scroller (src/st_scroll.c).  usage: python tools/gfx/mkfont.py"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
d = open(os.path.join(HERE, "..", "..", "gfx", "Antic.chr"), "rb").read()
assert len(d) == 512, len(d)
out = ["/* font_antic.c - generated by tools/gfx/mkfont.py from gfx/Antic.chr: the 8 x 8 font of the Atari 8 bit flight, 64 characters in screen code order (index = ATASCII code - 32: space, ! .. ?, @, A .. Z, [ backslash ] ^ _), bit 7 = left pixel */",
       "const unsigned char fontAntic[64][8] = {"]
for i in range(64):
    ch = chr(32 + i)
    out.append("\t{%s},  /* %d '%s' */" % (",".join("0x%02X" % b for b in d[i * 8:i * 8 + 8]), i, ch.replace("\\", "backslash")))
out.append("};")
open(os.path.join(HERE, "..", "..", "src", "font_antic.c"), "w").write("\n".join(out) + "\n")
print("src/font_antic.c written")
