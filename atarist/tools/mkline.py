"""mkline.py [cull|nocull] [out]: writes src/flight_line.asm (the byte line routine of the flight, version 2: word stack, piece culling, tables in the plot).  python tools/mkline.py cull src/flight_line.asm"""
import sys

CULL = 1 if (len(sys.argv) < 2 or sys.argv[1] != "nocull") else 0
_n = [0]


def tag():
    _n[0] += 1
    return _n[0]


def plot():
    """plot of (d0 = column, d4 = y): ridge buffer test, update, one pixel of the picture row"""
    t = tag()
    return f"""	move.b	(a2,d0.w),d5			; highest ridge value so far in this column
	cmp.b	d5,d4
	bls.s	.h{t}				; y <= fLineBuf[x]: hidden
	move.b	(a6,d4.w),(a2,d0.w)		; fLineBuf[x] = y, or $FF when the column is closed (y >= yTop): fLbMap
	add.w	d4,d4
	add.w	d4,d4				; y * 4
	movea.l	(a5,d4.w),a1			; address of the picture row in plane 0 (the rows above yTop have the address of the top row)
	ifd	UW
	move.w	d0,d5
	add.w	d5,d5
	move.w	(a3,d5.w),d5			; byte offset of the column + the water ripple of that column (a signed number of rows * stride): fColOffW, words
	else
	moveq	#0,d5
	move.b	(a3,d0.w),d5			; byte offset of the column
	endc
	move.b	(a4,d0.w),d6			; pixel mask
	or.b	d6,(a1,d5.w)
	ifgt	ROWREP-1
	adda.w	fCfg+2,a1			; next screen row
	or.b	d6,(a1,d5.w)
	endc
	ifgt	ROWREP-2
	adda.w	fCfg+2,a1
	or.b	d6,(a1,d5.w)
	endc
.h{t}:
"""


cull_code = f"""
	; ---- piece culling: the pixels of a piece can't be higher than max(y0, y1) + n / 2 + 3 (the sum of the largest displacements), so if every column of it already holds a ridge value
	; >= that bound nothing of it can be plotted: skip the whole piece (exact: no wrap of the byte arithmetic can happen when min(y0, y1) >= n / 2 + 3, and bounds over 255 are not tried).
	moveq	#0,d5
	move.b	(a2,d0.w),d5			; fLineBuf[X]
	cmp.w	d2,d5
	bls	.nocull				; the piece starts visible: certainly not hidden
	move.w	d4,d6
	addq.w	#3,d6
	lsr.w	#1,d6
	addq.w	#3,d6				; half = (n >> 1) + 3
	move.w	ZWY(a0),d7			; y1
	cmp.w	d7,d2
	bhs.s	.y0hi
	move.w	d7,d5
	add.w	d6,d5				; bound = y1 + half
	cmp.w	d6,d2
	blo	.nocull				; min(y0, y1) < half: a byte wrap is possible: no culling
	bra.s	.chk
.y0hi:	move.w	d2,d5
	add.w	d6,d5				; bound = y0 + half
	cmp.w	d6,d7
	blo	.nocull
.chk:	cmp.w	#255,d5
	bhi	.nocull
	lea	(a2,d0.w),a1
	move.w	d4,d6
	addq.w	#2,d6				; n - 1
.scan:	cmp.b	(a1)+,d5			; bound > fLineBuf[c]: a column that can show a pixel
	bhi.s	.nocull
	dbra	d6,.scan
	bra	.pop				; hidden: the state after the piece (X = ZX, z84 = ZY, z86 = ZH)
""" if CULL else ""

asm = f"""; flight_line.asm - the byte line routine of the fractal flight (Line51C of flight_core.c, LB51C of the game / line51 of the 800XL port) with the
; pixel plot (PlotCol + planar PlotPixel) inlined, for the 68000.  vasm, Motorola syntax.  Version 2 (generated by mkline.py, tools/mkline.py).
;
;   void Line51CAsm(int X, int yi, int z84, int z86);        (C calling convention: arguments on the stack, d2-d7/a2-a6 are saved here)
;
;   X      column of end 1 (end 1 = X, z84 (y), z86 (h));  yi = index of the stack top;  end 2 = the stack top ZX/ZY/ZH[yi]
;   Halves the piece (pushing midpoints with the fractal displacement) until it is 1 or 2 columns wide, plots, pops, goes on to the right.
;
; Differences to version 1 (the results are bit for bit the same, checked by the benchmark checksum and the host test tools/ap/ap_cull.c):
;   - the stack of the pieces is made of words (fZW, 3 arrays of 50 words) and is walked with a pointer: no byte extension, no indexed addressing; the byte stacks fZ are copied at the entry
;   - the end of the view (X >= colHi) is tested only when X changes (after a piece is done), not at every bisection
;   - n = ZX - X comes from one subtraction;  z86 is kept as z86 + 1 (the sum with the h of the other end needs no further add);  the displacement widths come from m = n >> 1
;   - the plot: fLbMap gives the new ridge value (y, or $FF if y >= yTop) and fRowAddr has entries up to y = 255: no compare, no clamp
;   - a piece of 3 or more columns whose columns all hold a ridge value above anything it can draw is skipped
;
;   registers:  d0 = X (word)   d1 = colHi   d2 = z84 (end 1 y)   d3 = z86 + 1   d4..d7 temporaries
;               a0 = top of the word stack (ZX word; ZY at +100, ZH at +200)   a1 = temporary
;               a2 = fLineBuf  a3 = fColOff  a4 = fMask  a5 = fRowAddr  a6 = fLbMap

	section	.text,code

	xref	fZ
	xref	fLineBuf
	xref	fColOff
	ifd	UW
	xref	fColOffW
	endc
	xref	fMask
	xref	fRowAddr
	xref	fLbMap
	xref	fCfg
	xdef	Line51CAsm
	xdef	Line51CCore

	ifnd	ROWREP
ROWREP	equ	3				; picture rows per ridge row (-DROWREP=1 on the Atari ST)
	endc

ZY	equ	48
ZH	equ	96
ZWY	equ	100
ZWH	equ	200

Line51CAsm:
	movem.l	d2-d7/a2-a6,-(sp)		; 11 registers = 44 bytes, + the return address
	move.l	48(sp),d0			; X
	move.l	52(sp),d1			; yi
	move.l	56(sp),d2			; z84
	move.l	60(sp),d3			; z86
	bsr	Line51CCore
	movem.l	(sp)+,d2-d7/a2-a6
	rts

; the same with the arguments in registers (d0 = X, d1 = yi, d2 = z84, d3 = z86), for DrawEdgeAsm; clobbers every register except sp
Line51CCore:
	lea	fZ,a0
	lea	fZW,a1
	move.w	d1,d4				; yi: copy the records 0 .. yi of the byte stacks to the word stack
.cv:	moveq	#0,d5
	move.b	(a0),d5
	move.w	d5,(a1)
	moveq	#0,d5
	move.b	ZY(a0),d5
	move.w	d5,ZWY(a1)
	moveq	#0,d5
	move.b	ZH(a0),d5
	move.w	d5,ZWH(a1)
	addq.l	#1,a0
	addq.l	#2,a1
	dbra	d4,.cv
	subq.l	#2,a1
	movea.l	a1,a0				; the top record
	lea	fLineBuf,a2
	ifd	UW
	lea	fColOffW,a3
	else
	lea	fColOff,a3
	endc
	lea	fMask,a4
	lea	fRowAddr,a5
	lea	fLbMap,a6
	moveq	#0,d1
	move.b	fCfg,d1				; colHi
	addq.w	#1,d3				; z86 + 1

.loop:
	cmp.b	d1,d0				; X >= colHi: done
	bhs	.done
.step:
	move.w	(a0),d4
	sub.w	d0,d4				; n = ZX - X
	subq.w	#3,d4				; n - 3
	bcs	.leaf				; n = 1 or 2: the end of the recursion
{cull_code}
	; ---- wider: push the midpoint with the fractal displacement
.nocull:
	move.w	d4,d5
	addq.w	#3,d5
	lsr.w	#1,d5				; m = n >> 1 = mid - X
	move.w	d0,d6
	add.w	d5,d6				; mid = X + m
	move.w	d6,2(a0)			; ZX[yi+1] = mid
	move.w	ZWH(a0),d7
	add.w	d3,d7				; t = z86 + ZH[yi] + 1 (9 bits)
	move.w	d2,d6
	add.w	ZWY(a0),d6			; t2 = z84 + ZY[yi]
	move.w	d6,d4				; (bit 0 = the carry out of the ror)
	lsr.w	#1,d6				; a = t2 >> 1
	tst.b	d7
	bpl.s	.nodisp				; the h byte is below $80: no displacement
	cmp.w	#256,d7
	bhs.s	.carry
	; h sum without carry: a = a - ((m - 1) >> 1) - (1 - c2)   (byte arithmetic)
	subq.w	#1,d5
	lsr.w	#1,d5
	sub.b	d5,d6
	btst	#0,d4
	bne.s	.nodisp
	subq.b	#1,d6
	bra.s	.nodisp
.carry:	; h sum with carry: a = min(255, a + (m >> 1) + c2)
	lsr.w	#1,d5
	add.w	d5,d6
	btst	#0,d4
	beq.s	.nc2
	addq.w	#1,d6
.nc2:	cmp.w	#255,d6
	bls.s	.nodisp
	move.w	#255,d6
.nodisp:
	andi.w	#$FF,d7
	move.w	d7,ZWH+2(a0)			; ZH[yi+1] = t & $FF
	move.w	d6,ZWY+2(a0)			; ZY[yi+1] = a
	addq.l	#2,a0
	bra	.step

	; ---- one or two columns
.leaf:
	addq.w	#1,d4
	bne.s	.one				; n = 1
	; ---- two columns: plot the middle ((ZY + z84 + 1) >> 1), then the end (ZY)
	move.w	ZWY(a0),d4
	move.w	d4,d7
	add.w	d2,d4
	addq.w	#1,d4
	lsr.w	#1,d4
{plot()}	addq.w	#1,d0				; X + 1
	move.w	d7,d4				; ZY (the plot uses d4 .. d6 and a1, not d7)
{plot()}	bra.s	.pop
	; ---- one column
.one:
	move.w	ZWY(a0),d4
{plot()}
	; ---- pop: the next piece starts at the end of this one
.pop:
	move.w	(a0),d0				; X = ZX
	move.w	ZWY(a0),d2			; z84 = ZY
	move.w	ZWH(a0),d3
	addq.w	#1,d3				; z86 + 1
	subq.l	#2,a0
	cmpa.l	#fZW,a0
	bhs	.loop
.done:
	rts

	section	.bss,bss
fZW:	ds.w	150
"""
open(sys.argv[2] if len(sys.argv) > 2 else "src/flight_line.asm", "w").write(asm)
print("flight_line.asm written, cull", CULL)
